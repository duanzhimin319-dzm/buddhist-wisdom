MIN_DATE = min(FESTIVALS)
MAX_DATE = max(FESTIVALS)


def query(day: date) -> str:
    key = day.isoformat()
    lines = [f"公历: {key}"]
    if key in FESTIVALS:
        name = FESTIVALS[key]
        lines.append(f"节日: 今天是{name}")
    else:
        lines.append("节日: 无（平日）")
        # 找下一个节日
        d = day
        for _ in range(400):
            d += timedelta(days=1)
            if d.isoformat() in FESTIVALS:
                delta = (d - day).days
                lines.append(f"下一节日: {FESTIVALS[d.isoformat()]}（{delta}天后，{d.isoformat()}）")
                break
    if key < MIN_DATE or key > MAX_DATE:
        lines.append(f"注意: 查询日期超出内置范围（{MIN_DATE} ~ {MAX_DATE}），"
                     "结果仅供参考，请换算农历后核对 references/festivals.md 节日总表。")
    return "\n".join(lines)


